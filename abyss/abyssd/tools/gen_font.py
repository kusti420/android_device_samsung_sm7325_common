#!/usr/bin/env python3
"""Generate abyssd's baked 1-bit bitmap font (src/font_data.rs).

Run offline on a PC (needs Pillow); the output is committed, the build never
runs this script.

    python3 tools/gen_font.py \
        --font /usr/share/fonts/TTF/DejaVuSansMono.ttf \
        --fallback /usr/share/fonts/TTF/DejaVuSans.ttf \
        --small 40 --body 48 --big 72 > src/font_data.rs

Source font: DejaVu Sans Mono 2.37 (fallback DejaVu Sans 2.37 for any symbol
the mono face lacks). License: Bitstream Vera Fonts license + DejaVu changes
in the public domain (permissive, allows embedding and redistribution of
derived bitmaps). See README.md.

Glyph rows are packed MSB-first, each row padded to a whole byte.
"""

import argparse
import sys

from PIL import Image, ImageDraw, ImageFont

# Symbols the UI uses beyond the Latin blocks.
SYMBOLS = "▸▲▼●✓≈·–—…→←›‹“”‘’€°×−↑↓⇅▮"


def body_charset():
    cps = list(range(0x20, 0x7F))          # ASCII
    cps += list(range(0xA0, 0x100))        # Latin-1 Supplement
    cps += list(range(0x100, 0x180))       # Latin Extended-A
    cps += [ord(c) for c in SYMBOLS]
    return sorted(set(cps))


def big_charset():
    # Titles and folder names: the same coverage as BODY.
    return body_charset()


def render(font, ch):
    """Return (bitmap rows as list[list[int]], x_off, y_off_from_baseline, w, h)."""
    size = font.size
    canvas = Image.new("L", (size * 3, size * 3), 0)
    draw = ImageDraw.Draw(canvas)
    draw.fontmode = "1"  # no anti-aliasing: monochrome rasterisation
    ox, oy = size, size * 2  # origin (left, baseline)
    draw.text((ox, oy), ch, font=font, fill=255, anchor="ls")
    bbox = canvas.getbbox()
    if bbox is None:
        return [], 0, 0, 0, 0
    x0, y0, x1, y1 = bbox
    crop = canvas.crop(bbox)
    w, h = crop.size
    px = crop.load()
    rows = [[1 if px[x, y] >= 128 else 0 for x in range(w)] for y in range(h)]
    return rows, x0 - ox, y0 - oy, w, h


def missing(font, ch):
    """True when `font` has no glyph for ch (renders the same as .notdef)."""
    a = render(font, ch)
    b = render(font, "￿")
    return a[0] == b[0] and a[3] == b[3]


def build(name, path, fallback, size, cps):
    font = ImageFont.truetype(path, size)
    fb = ImageFont.truetype(fallback, size) if fallback else None
    ascent, descent = font.getmetrics()
    glyphs = []
    bits = bytearray()
    for cp in cps:
        ch = chr(cp)
        f = font
        if cp > 0x20 and missing(font, ch):
            if fb is None or missing(fb, ch):
                print(f"warning: U+{cp:04X} missing, skipped", file=sys.stderr)
                continue
            f = fb
        rows, x, y, w, h = render(f, ch)
        adv = int(round(f.getlength(ch)))
        off = len(bits)
        for r in rows:
            for bx in range(0, w, 8):
                byte = 0
                for i in range(8):
                    if bx + i < w and r[bx + i]:
                        byte |= 0x80 >> i
                bits.append(byte)
        # y is relative to the baseline (negative = above). Store relative to
        # the top of the line box instead: top = baseline - ascent.
        glyphs.append((cp, adv, x, y + ascent, w, h, off))
    out = []
    out.append(f"pub static {name}: FontData = FontData {{")
    out.append(f"    size_px: {size},")
    out.append(f"    ascent: {ascent},")
    out.append(f"    line_h: {ascent + descent},")
    out.append(f"    glyphs: &[")
    for g in glyphs:
        out.append("        Glyph {{ cp: 0x{:04X}, adv: {}, x: {}, y: {}, w: {}, h: {}, off: {} }},".format(*g))
    out.append("    ],")
    out.append(f"    bits: {name}_BITS,")
    out.append("};")
    out.append("")
    # Byte string literal: compact and fast for rustc.
    lit = "".join(f"\\x{b:02x}" for b in bits)
    lines = [lit[i:i + 96] for i in range(0, len(lit), 96)]
    out.append(f"static {name}_BITS: &[u8] = b\"\\")
    for ln in lines:
        out.append(ln + "\\")
    out.append("\";")
    return "\n".join(out), len(glyphs), len(bits)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="/usr/share/fonts/TTF/DejaVuSansMono.ttf")
    ap.add_argument("--bold", default="/usr/share/fonts/TTF/DejaVuSansMono-Bold.ttf")
    ap.add_argument("--fallback", default="/usr/share/fonts/TTF/DejaVuSans.ttf")
    ap.add_argument("--small", type=int, default=40)
    ap.add_argument("--body", type=int, default=48)
    ap.add_argument("--big", type=int, default=72)
    a = ap.parse_args()
    parts = [
        build("SMALL", a.font, a.fallback, a.small, body_charset()),
        build("BODY", a.font, a.fallback, a.body, body_charset()),
        build("BODY_BOLD", a.bold, a.fallback, a.body, body_charset()),
        build("BIG", a.font, a.fallback, a.big, big_charset()),
    ]
    print("// @generated by tools/gen_font.py - do not edit by hand.")
    print(f"// Source: DejaVu Sans Mono (+ Bold; fallback DejaVu Sans): SMALL {a.small} px,")
    print(f"// BODY {a.body} px, BODY_BOLD {a.body} px, BIG {a.big} px.")
    print("// 1-bit, rows MSB-first padded to bytes. License: Bitstream Vera / DejaVu (see README.md).")
    for name, (_, n, b) in zip(["SMALL", "BODY", "BODY_BOLD", "BIG"], parts):
        print(f"// {name}: {n} glyphs, {b} bytes.")
    print()
    print("use crate::font::{FontData, Glyph};")
    for text, _, _ in parts:
        print()
        print(text)


if __name__ == "__main__":
    main()
